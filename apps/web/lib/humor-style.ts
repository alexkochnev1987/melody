import { z } from 'zod';

/** Human humor style is scoped to an individual generation request; no DB migration. */
export const humorStyleSchema = z.enum(['conversational', 'ironic', 'absurd', 'warm']);
export type HumorStyle = z.infer<typeof humorStyleSchema>;

const voice: Record<HumorStyle, string> = {
  conversational: 'Звучит как спонтанная шутка остроумного друга за столом, коротко и естественно.',
  ironic: 'Лёгкая самоирония и наблюдательность, без злобы, грубости и сложных конструкций.',
  absurd: 'Немного нелепая, но понятная бытовая ситуация с неожиданным поворотом.',
  warm: 'Добрый, тёплый и простой юмор, понятный компании друзей разного возраста.',
};

export function humanHumorGuide(style: HumorStyle): string {
  return [
    voice[style],
    'Пиши живым разговорным русским: без канцелярита, книжных вступлений и длинных метафор.',
    'Избегай клише AI: «представьте себе», «эта песня о том, как», «когда жизнь подкидывает», «погрузитесь в мир», «это история про».',
    'Одна понятная ситуация, одна неожиданная смешная деталь. Не надо быть смешным любой ценой.',
    'Сначала мысленно придумай человеческую шутку, затем сократи её до одного предложения (желательно до 120 символов).',
    'Варианты для одной песни должны отличаться идеей, а не перестановкой слов.',
    'Плохой пример: «Эта песня отражает сложные эмоциональные переживания».',
    'Хороший пример ритма и интонации: «Обещал лечь пораньше, а уже споришь с холодильником». Не повторяй этот пример.',
  ].join('\n');
}
